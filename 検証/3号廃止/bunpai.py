#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""拠出金按分据置型で「誰の年金が増えるか」を確かめる

按分据置型では基礎年金が上がる一方、報酬比例は下がる（基礎年金の水準が高い
ままだと拠出金も高いままなので、厚生年金がその分を吸収する。2段階均衡）。
基礎年金は**定額**、報酬比例は**賃金比例**なので、賃金が高い人ほど比例の
減少が効く。どこかで損得が逆転しないかを見る。

**所得代替率の「うち基礎」は夫婦2人分である。** モデル世帯は「夫が厚生年金に
40年加入、妻が40年間第3号」で、基礎年金は2本、報酬比例は夫の1本。
したがって損益分岐は世帯の形で変わる。

  片働き夫婦（モデル世帯）   k* = Δ基礎      ÷ |Δ比例|
  単身・共働きの1人           k* = (Δ基礎/2) ÷ |Δ比例|

k は本人の賃金 ÷ モデルの賃金（男子平均）。

使い方: python3 検証/3号廃止/bunpai.py
"""
import importlib.util
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
_spec = importlib.util.spec_from_file_location(
    "sango", os.path.join(HERE, "analyze_sango.py"))
_m = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(_m)

SUURI = os.path.join(ROOT, "work", "suuri", "rev2024")
CASES = (("3003", "過去30年投影"), ("3001", "高成長実現"))
SAISHU_NENDO = 2120       # 調整終了後の所得代替率を取る年度
JISSHI = 2027

# 取りうる k の目安（概算。出力ファイルからは取れないので出どころを書いておく）
HYOJUN_JOGEN = 650000     # 標準報酬月額の上限（最高等級）
AVG_SOHOU = 405000        # 平均総報酬（月）＝ ⑤の総報酬総額 230兆円（2024年度）
                          #   ÷ 被保険者 4,733万人 ÷ 12。賞与を均して含む


def main():
    out = []
    w = out.append
    w("# 拠出金按分据置型で誰の年金が増えるか\n")
    w("按分据置型では基礎年金が上がり、報酬比例が下がる（2段階均衡）。基礎年金は**定額**、"
      "報酬比例は**賃金比例**なので、賃金が高い人ほど比例の減少が効く。"
      "どこかで損得が逆転しないかを見る。`bunpai.py` が出力ファイルから計算したもの。\n")
    w("**所得代替率の「うち基礎」は夫婦2人分である。** モデル世帯は「夫が厚生年金に40年加入、"
      "妻が40年間第3号」で、基礎年金は2本、報酬比例は夫の1本。損益分岐は世帯の形で変わる。\n")
    w("```")
    w("  片働き夫婦（モデル世帯）  k* = Δ基礎       ÷ |Δ比例|")
    w("  単身・共働きの1人          k* = (Δ基礎 / 2) ÷ |Δ比例|")
    w("  k = 本人の賃金 ÷ モデルの賃金")
    w("```\n")
    w("| ケース | Δ基礎（夫婦2人分） | Δ比例 | k*（片働き夫婦） | k*（単身・共働き） |")
    w("|---|---|---|---|---|")
    kmin = None
    for case, name in CASES:
        b = _m.load_run(SUURI, case, "000", "000")
        s = _m.load_run(SUURI, case, "501", "501")
        if b is None or s is None:
            print(f"（未計算）{name}", file=sys.stderr)
            continue
        y = SAISHU_NENDO
        dk = s["rr_kiso"][y] - b["rr_kiso"][y]
        dh = s["rr_hirei"][y] - b["rr_hirei"][y]
        if dh >= -1e-9:
            w(f"| {name} | {dk:+.2f}pt | {dh:+.2f}pt | —（比例が減らない） | —（比例が減らない） |")
        else:
            k2, k1 = dk / -dh, dk / 2 / -dh
            kmin = k1 if kmin is None else min(kmin, k1)
            w(f"| {name} | {dk:+.2f}pt | {dh:+.2f}pt | {k2:.2f} 倍 | **{k1:.2f} 倍** |")
    w("")
    if kmin is not None:
        cap = HYOJUN_JOGEN / AVG_SOHOU
        w("## その倍率に届く人はいるか\n")
        w("| 項目 | 値 |")
        w("|---|---|")
        w(f"| 平均総報酬（月、賞与を均して含む。概算） | 約 {AVG_SOHOU:,}円 |")
        w(f"| 標準報酬月額の上限 | {HYOJUN_JOGEN:,}円 |")
        w(f"| 上限 ÷ 全体の平均（月給だけで見た k の上限の目安） | 約 {cap:.1f} 倍 |")
        w("| モデルの賃金 | 男子の平均なので全体の平均より高い。上限 ÷ モデルの賃金はこれより小さい |")
        w("| 賞与 | 標準賞与額は1回150万円までを別枠で算入するので、賞与の多い人は k がさらに上がる |")
        w("")
        w(f"**単身・共働きの1人は、賃金がモデルの約 {kmin:.1f} 倍を超えると損をする。** "
          f"月給だけで見た上限（全体平均比で約 {cap:.1f} 倍、モデル比ではそれ以下）の**すぐ上**に"
          "あたる。月給だけでは届きにくいが、賞与の多い高所得者は越えうる（推定）。"
          "つまり過去30年投影では、**高所得の単身者・共働き世帯は損益分岐の境目にいて、"
          "一部は報酬比例の減少が基礎年金の増加を上回る**。「全員が得をする」とは言えない。\n")
        w("片働き夫婦（モデル世帯）は損益分岐が高く、上限に張りついても得をする。ただしこの世帯は、"
          "妻がまさに新しく国民年金の保険料（2027年度で月約17,600円）を払う世帯である。"
          "所得代替率の分母は夫の手取りなので、**その負担は所得代替率には現れない**。\n")
        w("高成長実現ケースは報酬比例が減らないので、世帯の形によらず給付は減らない"
          "（片働き夫婦の保険料負担は別）。\n")
    w("> **注意。** 所得代替率はモデル世帯の値で、加入期間・賞与の扱いはモデルのまま固定"
      "している。個々人の年金額を示すものではない。k の上限は概算。\n")
    res = os.path.join(HERE, "分配.md")
    with open(res, "w", encoding="utf-8") as f:
        f.write("\n".join(out) + "\n")
    print("書き出し:", res)
    print("\n".join(out))


if __name__ == "__main__":
    main()
