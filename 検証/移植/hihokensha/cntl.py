def _pick(scan, msgs, ng):
    """`scanf` で読んで、表に無ければ原本と同じく `exit(2)`。"""
    v = scan.d()
    msg = msgs.get(v)
    if msg is None:
        print(ng, file=sys.stderr)
        raise SystemExit(2)
    print(msg)
    return v


